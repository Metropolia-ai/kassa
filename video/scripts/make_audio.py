"""Generate one voice-over mp3 per scene from docs/video-script.md and write src/audioConfig.ts.

Run from anywhere:  /root/Frappua/projects/paypal-agent/.venv/bin/python video/scripts/make_audio.py [--force]
Texts are taken verbatim from the Voice-over column of the script table.
"""
import json, re, subprocess, sys
from pathlib import Path

VIDEO = Path(__file__).resolve().parent.parent
SCRIPT = VIDEO.parent / "docs" / "video-script.md"
AUDIO = VIDEO / "public" / "audio"
PY = "/root/Frappua/projects/paypal-agent/.venv/bin/python"
IDS = ["intro", "rules", "scene1", "scene2", "scene3", "chat", "closing"]
FPS = 30

def parse_rows():
    rows = []
    for line in SCRIPT.read_text().splitlines():
        m = re.match(r"^\|\s*(\d+):(\d\d)[–-](\d+):(\d\d)\s*\|(.*)\|(.*)\|\s*$", line)
        if m:
            a = int(m[1]) * 60 + int(m[2]); b = int(m[3]) * 60 + int(m[4])
            rows.append({"min": b - a, "text": m[6].strip()})
    assert len(rows) == len(IDS), f"expected {len(IDS)} rows, got {len(rows)}"
    return rows

def duration(p):
    out = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(p)])
    return float(out.strip())

def main():
    force = "--force" in sys.argv
    AUDIO.mkdir(parents=True, exist_ok=True)
    entries = []
    for sid, row in zip(IDS, parse_rows()):
        mp3 = AUDIO / f"{sid}.mp3"
        if force or not mp3.exists():
            subprocess.check_call([PY, "-m", "edge_tts", "--voice", "en-GB-RyanNeural", "--rate=-5%",
                                   "--text", row["text"], "--write-media", str(mp3),
                                   "--write-subtitles", str(AUDIO / f"{sid}.srt")])
        d = duration(mp3)
        entries.append({"id": sid, "file": f"audio/{sid}.mp3", "durationSeconds": round(d, 3),
                        "minSeconds": row["min"], "text": row["text"]})
        print(f"{sid:8s} audio {d:6.2f}s  min {row['min']}s")
    body = ",\n".join("  " + json.dumps(e, ensure_ascii=False) for e in entries)
    ts = f"""// Generated by scripts/make_audio.py. Do not edit by hand.
export type AudioEntry = {{ id: string; file: string; durationSeconds: number; minSeconds: number; text: string }};
export const FPS = {FPS};
export const AUDIO: AudioEntry[] = [
{body}
];
"""
    (VIDEO / "src" / "audioConfig.ts").write_text(ts)

main()
